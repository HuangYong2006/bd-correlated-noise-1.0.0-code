"""Export manuscript numbers directly from the regenerated source tables."""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]
source = ROOT / 'data/analysis/revision_20261026'
s = json.loads((source / 'summary.json').read_text(encoding='utf-8'))
n = json.loads((source / 'noise_validation.json').read_text(encoding='utf-8'))

def exponent(generator, theta):
    return next(v for v in s['exponents'] if v['generator'] == generator and abs(v['theta']-theta)<5e-5)

def cell(generator, theta, L):
    return next(v for v in s['cells'] if v['generator']==generator and v['L']==L and abs(v['theta']-theta)<5e-5)

lines = ['% Generated by code/export_revision_tables.py from revision_20261026 source data.']
def define(name, value):
    lines.append('\\newcommand{\\' + name + '}{' + value + '}')

for name, generator, theta in [
    ('AlphaSharedQuarter','shared',.25),('AlphaFgnQuarter','fgn',.25),
    ('AlphaPowerQuarter','powerlaw',.25),('AlphaFgnZero','fgn',0),
    ('AlphaSharedZero','shared',0),('AlphaPowerZero','powerlaw',0),
    ('AlphaFgnStrong','fgn',.4),('AlphaSharedStrong','shared',.4),
    ('AlphaPowerStrong','powerlaw',.4)]:
    r=exponent(generator,theta)
    define(name, f"{r['alpha']:.3f}" + r'\pm' + f"{r['alpha_err']:.3f}")
maxdiff=max(abs(exponent('fgn',t)['alpha']-exponent('powerlaw',t)['alpha']) for t in s['protocol']['thetas'])
define('AlphaFilterMaxDiff',f'{maxdiff:.4f}')
define('NullFloorSmall',f"{cell('fgn',0,32)['Hnull_mean']:.4f}")
define('NullFloorLarge',f"{cell('fgn',0,512)['Hnull_mean']:.4f}")
define('NullFloorRatio',f"{cell('fgn',0,32)['Hnull_mean']/cell('fgn',0,512)['Hnull_mean']:.2f}")
for name,g,t in [('PflatFgnZero','fgn',0),('PflatFgnStrong','fgn',.4),('PflatSharedZero','shared',0),('PflatSharedStrong','shared',.4)]:
    r=cell(g,t,256); define(name,f"{r['p_flat']:.4f}"+r'\pm'+f"{r['p_flat_err']:.4f}")
define('WidthSharedStrong',f"{cell('shared',.4,256)['W']:.2f}")
define('WidthFgnStrong',f"{cell('fgn',.4,256)['W']:.2f}")
define('WidthStrongRatio',f"{cell('shared',.4,256)['W']/cell('fgn',.4,256)['W']:.2f}")
define('LateRatioMin',f"{min(v['late_ratio'] for v in s['cells']):.3f}")
define('LateRatioMax',f"{max(v['late_ratio'] for v in s['cells']):.3f}")
check=next(v for v in n['series'] if v['generator']=='fgn' and v['theta']==.25 and v['L']==32)
define('NoiseTimeMeasured',f"{check['C_time'][0]:.4f}")
define('NoiseTimeTarget',f"{check['target_time'][0]:.4f}")
define('NoiseLegacyTime',f"{n['legacy']['C_time'][0]:.4f}")
define('NoiseLegacySpace',f"{n['legacy']['C_space'][0]:.4f}")
rows=[]
for t in s['protocol']['thetas']:
    label=r'1/6' if abs(t-1/6)<1e-5 else f'{t:.2f}'
    values=[]
    for g in ['shared','powerlaw','fgn']:
        r=exponent(g,t);values.append(f"${r['alpha']:.3f}"+r'\pm'+f"{r['alpha_err']:.3f}$")
    rows.append('$'+label+'$ & '+' & '.join(values)+r' \\')
define('RevisionAlphaRows','\n'+'\n'.join(rows)+'\n')
(ROOT/'manuscript/revision_results.tex').write_text('\n'.join(lines)+'\n',encoding='utf-8')
print('Exported',len(lines)-1,'data-derived LaTeX commands')
