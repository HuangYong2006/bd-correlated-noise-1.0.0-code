"""
Verify (and optionally delete) campaign cell files.

A cell that was being written when a job was killed is truncated and will fail
np.load.  This utility lists such files and, with --delete-bad, removes them so
that a subsequent run with --skip-existing regenerates them.

Usage: python code/verify_cells.py --tag main --rule bd --delete-bad
"""

from __future__ import annotations

import argparse
import glob
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

ap = argparse.ArgumentParser()
ap.add_argument("--tag", required=True)
ap.add_argument("--rule", default="bd")
ap.add_argument("--delete-bad", action="store_true")
args = ap.parse_args()

d = os.path.join(ROOT, "data", "raw", args.tag)
files = sorted(glob.glob(os.path.join(d, f"{args.rule}_*.npz")))
ok, bad = 0, []
for f in files:
    try:
        z = np.load(f, allow_pickle=False)
        _ = z["profiles"].shape, z["w_series"].shape, z["check_times"].shape
        z.close()
        ok += 1
    except Exception as e:
        bad.append((f, type(e).__name__))

print(f"{args.tag}/{args.rule}: {ok} readable, {len(bad)} bad, {len(files)} total")
for f, e in bad:
    print(f"  BAD  {os.path.basename(f)}  ({e})")
    if args.delete_bad:
        try:
            os.remove(f)
            print(f"       deleted -> will be regenerated by a --skip-existing run")
        except OSError as err:
            print(f"       could not delete: {err}")
